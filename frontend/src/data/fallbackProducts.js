export function getFallbackDeals() {
  return FALLBACK_PRODUCTS.filter((p) => p.dealOfTheDay);
}

export function getFallbackFeatured() {
  return FALLBACK_PRODUCTS.filter((p) => p.featured);
}

export function getFallbackTopOffers() {
  return FALLBACK_PRODUCTS.filter((p) => p.topOffer);
}

export function getFallbackProductById(id) {
  const numericId = Number(id);
  const found = FALLBACK_PRODUCTS.find((p) => p.id === numericId);
  return found || FALLBACK_PRODUCTS[0];
}

export function filterFallbackProducts({
  keyword,
  categoryId,
  categorySlug,
  brand,
  minPrice,
  maxPrice,
  minRating,
  sortBy = 'popularity',
  _sortDir = 'desc',
  page = 0,
  size = 30,
} = {}) {
  let list = [...FALLBACK_PRODUCTS];

  if (keyword) {
    const q = keyword.toLowerCase().trim();
    list = list.filter(
      (p) =>
        p.title.toLowerCase().includes(q) ||
        p.description.toLowerCase().includes(q) ||
        p.brand.toLowerCase().includes(q) ||
        (p.categoryName && p.categoryName.toLowerCase().includes(q)) ||
        (p.categorySlug && p.categorySlug.toLowerCase().includes(q)) ||
        (p.specifications && p.specifications.toLowerCase().includes(q))
    );
  }

  if (categoryId) {
    list = list.filter((p) => p.categoryId === Number(categoryId));
  } else if (categorySlug) {
    if (categorySlug === 'top-offers') {
      list = list.filter((p) => p.topOffer);
    } else {
      list = list.filter((p) => p.categorySlug === categorySlug);
    }
  }

  if (brand) {
    list = list.filter((p) => p.brand.toLowerCase() === brand.toLowerCase());
  }

  if (minPrice !== undefined && minPrice !== '') {
    list = list.filter((p) => p.price >= Number(minPrice));
  }

  if (maxPrice !== undefined && maxPrice !== '') {
    list = list.filter((p) => p.price <= Number(maxPrice));
  }

  if (minRating !== undefined && minRating !== '') {
    list = list.filter((p) => (p.rating || 0) >= Number(minRating));
  }

  if (sortBy === 'price_asc') {
    list.sort((a, b) => a.price - b.price);
  } else if (sortBy === 'price_desc') {
    list.sort((a, b) => b.price - a.price);
  } else if (sortBy === 'newest') {
    list.sort((a, b) => b.id - a.id);
  } else {
    // popularity / default
    list.sort((a, b) => (b.ratingCount || 0) - (a.ratingCount || 0));
  }

  const start = page * size;
  const paginated = list.slice(start, start + size);

  return {
    content: paginated,
    totalElements: list.length,
    totalPages: Math.ceil(list.length / size) || 1,
    number: page,
    size,
  };
}
